export interface Props {
    icon: string;
    className?: string;
    style?: React.CSSProperties;
}

const Avatar: React.FC<{ label: string; className?: string; style?: React.CSSProperties }> = ({ label, className, style }) => {
    const text = label.slice(0, 3).toUpperCase();
    return (
        <svg viewBox="0 0 40 40" xmlns="http://www.w3.org/2000/svg" role="img" className={className} style={style}>
            <rect width="40" height="40" rx="20" fill="#6B7280" />
            <text x="50%" y="50%" dominantBaseline="central" textAnchor="middle" fill="#ffffff" fontSize={text.length > 2 ? "11" : "13"} fontFamily="sans-serif" fontWeight="bold">
                {text}
            </text>
        </svg>
    );
};

const FinancialFlagIcon: React.FC<Props> = props => {
    const IconComponent = icons[props.icon.toLowerCase()];
    return IconComponent
        ? <IconComponent className={props.className} style={props.style} />
        : <Avatar label={props.icon} className={props.className} style={props.style} />;
}

export default FinancialFlagIcon;
